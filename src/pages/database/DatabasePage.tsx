import React, { useState, useEffect, useRef } from 'react';
import './DatabasePage.scss';
import { db } from '../../services/db';
import {
  getSupabaseConfig,
  saveSupabaseConfig,
  clearSupabaseConfig,
  setDbMode,
  testSupabaseConnection,
  normalizeSupabaseUrl,
  DbMode,
} from '../../services/supabaseClient';
import { useToast } from '../../components/layout/ToastContext';
import {
  Lock,
  VpnKey,
  Person,
  Visibility,
  VisibilityOff,
  Shield,
  ExitToApp,
  Storage,
  CloudDone,
  CloudSync,
  Backup,
  Restore,
  Code,
  CheckCircle,
  ErrorOutline,
  Refresh,
  TableChart,
} from '@mui/icons-material';

const SCHEMA_SQL = `-- 1. Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    age INT DEFAULT 18,
    grade TEXT DEFAULT 'A',
    gender TEXT DEFAULT 'Male',
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Teachers Table
CREATE TABLE IF NOT EXISTS public.teachers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    age INT DEFAULT 35,
    subject TEXT NOT NULL,
    gender TEXT DEFAULT 'Female',
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    role TEXT DEFAULT 'Student',
    gender TEXT DEFAULT 'Male',
    date TEXT NOT NULL,
    status TEXT DEFAULT 'Present',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. IPO Watchlist Table
CREATE TABLE IF NOT EXISTS public.ipo_list (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    company TEXT NOT NULL,
    issue_size TEXT,
    price_range TEXT,
    min_investment TEXT,
    logo_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Users Table (for Database Hub Authentication)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    name TEXT,
    role TEXT DEFAULT 'admin',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. Seed Default Admin User
INSERT INTO public.users (username, password_hash, name, role)
VALUES ('rishabh', 'cmlzaGlAMTIz', 'Rishabh Kumar', 'admin')
ON CONFLICT (username) DO NOTHING;

-- 7. Row Level Security (RLS) - Allows public access with Anon Key
ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teachers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ipo_list ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public full access students" ON public.students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access teachers" ON public.teachers FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access attendance" ON public.attendance FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access ipo_list" ON public.ipo_list FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access users" ON public.users FOR ALL USING (true) WITH CHECK (true);

-- Synchronize sequence IDs so new auto-increment rows never conflict with seed IDs
SELECT setval(pg_get_serial_sequence('public.students', 'id'), COALESCE(max(id), 1)) FROM public.students;
SELECT setval(pg_get_serial_sequence('public.teachers', 'id'), COALESCE(max(id), 1)) FROM public.teachers;
SELECT setval(pg_get_serial_sequence('public.attendance', 'id'), COALESCE(max(id), 1)) FROM public.attendance;
SELECT setval(pg_get_serial_sequence('public.ipo_list', 'id'), COALESCE(max(id), 1)) FROM public.ipo_list;`;

type TableTab = 'students' | 'teachers' | 'attendance' | 'ipo' | 'users';

const DatabasePage: React.FC = () => {
  const { showToast } = useToast();
  const fileInputRef = useRef<HTMLInputElement>(null);

  // User Authentication from Database
  const [isAuthenticated, setIsAuthenticated] = useState<boolean>(() => {
    return sessionStorage.getItem('rishabh_db_auth') === 'true';
  });
  const [authUsername, setAuthUsername] = useState('rishabh');
  const [authPassword, setAuthPassword] = useState('');
  const [showPassword, setShowPassword] = useState(false);
  const [authError, setAuthError] = useState('');
  const [authenticating, setAuthenticating] = useState(false);
  const [currentUser, setCurrentUser] = useState<{ username: string; name: string; role: string } | null>(() => {
    const saved = sessionStorage.getItem('rishabh_db_user');
    return saved ? JSON.parse(saved) : null;
  });

  // DB Stats & Configuration
  const [stats, setStats] = useState({
    studentsCount: 0,
    teachersCount: 0,
    attendanceCount: 0,
    ipoCount: 0,
    totalRecords: 0,
  });

  const [config, setConfig] = useState(getSupabaseConfig());
  const [inputUrl, setInputUrl] = useState(config.url);
  const [inputKey, setInputKey] = useState(config.anonKey);
  const [currentMode, setCurrentMode] = useState<DbMode>(config.mode);

  const [testing, setTesting] = useState(false);
  const [testResult, setTestResult] = useState<{ success: boolean; message: string } | null>(null);
  const [syncing, setSyncing] = useState(false);
  const [showSql, setShowSql] = useState(false);

  // Live In-Hub Table Viewer
  const [activeTab, setActiveTab] = useState<TableTab>('students');
  const [tableData, setTableData] = useState<any[]>([]);
  const [tableLoading, setTableLoading] = useState(false);
  const [tableSearch, setTableSearch] = useState('');
  const [showRawJson, setShowRawJson] = useState(false);

  const handleLogin = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!authUsername.trim() || !authPassword.trim()) {
      setAuthError('Please enter both username and password.');
      return;
    }
    setAuthenticating(true);
    setAuthError('');
    try {
      const res = await db.users.authenticate(authUsername, authPassword);
      if (res.success && res.user) {
        sessionStorage.setItem('rishabh_db_auth', 'true');
        sessionStorage.setItem('rishabh_db_user', JSON.stringify(res.user));
        setIsAuthenticated(true);
        setCurrentUser(res.user);
        showToast(`Welcome back, ${res.user.name || res.user.username}! Database Hub unlocked. 🔓`, 'success');
        loadStats();
        loadTableData('students');
      } else {
        setAuthError(res.message || 'Authentication failed. Please verify credentials in the database.');
        showToast('Access Denied: Invalid database credentials', 'error');
      }
    } catch (err: any) {
      setAuthError(err?.message || 'Authentication failed.');
    } finally {
      setAuthenticating(false);
    }
  };

  const handleLogout = () => {
    sessionStorage.removeItem('rishabh_db_auth');
    sessionStorage.removeItem('rishabh_db_user');
    setIsAuthenticated(false);
    setCurrentUser(null);
    setAuthPassword('');
    showToast('Database Hub session locked 🔒', 'info');
  };

  const loadStats = async () => {
    try {
      const s = await db.getStats();
      setStats({
        studentsCount: s.studentsCount,
        teachersCount: s.teachersCount,
        attendanceCount: s.attendanceCount,
        ipoCount: s.ipoCount,
        totalRecords: s.totalRecords,
      });
      setConfig(getSupabaseConfig());
    } catch (e) {
      console.error('Failed to load DB stats:', e);
    }
  };

  const loadTableData = async (tab: TableTab) => {
    setTableLoading(true);
    try {
      if (tab === 'students') {
        const data = await db.students.getAll();
        setTableData(data);
      } else if (tab === 'teachers') {
        const data = await db.teachers.getAll();
        setTableData(data);
      } else if (tab === 'attendance') {
        const data = await db.attendance.getAll();
        setTableData(data);
      } else if (tab === 'ipo') {
        const data = await db.ipo.getAll();
        setTableData(data);
      } else if (tab === 'users') {
        const data = await db.users.getAll();
        // Mask passwords in view for safety
        setTableData(data.map((u: any) => ({ ...u, passwordHash: '••••••••' })));
      }
    } catch (e) {
      console.warn('Error loading table records:', e);
    } finally {
      setTableLoading(false);
    }
  };

  useEffect(() => {
    if (isAuthenticated) {
      loadStats();
      loadTableData(activeTab);
    }
  }, [isAuthenticated, activeTab]);

  const handleModeChange = (mode: DbMode) => {
    setCurrentMode(mode);
    setDbMode(mode);
    showToast(`Database mode changed to: ${mode.toUpperCase()}`, 'info');
    loadStats();
  };

  const handleTestConnection = async () => {
    setTesting(true);
    setTestResult(null);
    try {
      const cleanUrl = normalizeSupabaseUrl(inputUrl);
      if (cleanUrl && cleanUrl !== inputUrl) {
        setInputUrl(cleanUrl);
      }
      const res = await testSupabaseConnection(cleanUrl || inputUrl, inputKey);
      setTestResult({ success: res.success, message: res.message });
      if (res.success) {
        showToast('Supabase connection successful! 🚀', 'success');
      } else {
        showToast(res.message, 'error');
      }
    } catch (err: any) {
      setTestResult({ success: false, message: err.message || 'Connection test failed' });
    } finally {
      setTesting(false);
    }
  };

  const handleSaveCredentials = () => {
    const cleanUrl = normalizeSupabaseUrl(inputUrl);
    if (!cleanUrl.trim() || !inputKey.trim()) {
      showToast('Please enter both Supabase URL and Anon Key', 'warning');
      return;
    }
    if (cleanUrl !== inputUrl) {
      setInputUrl(cleanUrl);
    }
    saveSupabaseConfig(cleanUrl, inputKey);
    setConfig(getSupabaseConfig());
    showToast('Supabase credentials saved successfully! 💾', 'success');
    handleTestConnection();
  };

  const handleClearCredentials = () => {
    if (window.confirm('Clear stored Supabase credentials and return to Local Only mode?')) {
      clearSupabaseConfig();
      setInputUrl('');
      setInputKey('');
      setConfig(getSupabaseConfig());
      setTestResult(null);
      handleModeChange('local');
      showToast('Cloud credentials cleared', 'info');
    }
  };

  const handleSyncToCloud = async () => {
    setSyncing(true);
    try {
      const res = await db.syncLocalToCloud();
      if (res.success) {
        showToast(res.message, 'success');
      } else {
        showToast(res.message, 'error');
      }
      loadStats();
      loadTableData(activeTab);
    } catch (err: any) {
      showToast(err.message || 'Sync failed', 'error');
    } finally {
      setSyncing(false);
    }
  };

  const handleSyncFromCloud = async () => {
    setSyncing(true);
    try {
      const res = await db.syncCloudToLocal();
      if (res.success) {
        showToast(res.message, 'success');
      } else {
        showToast(res.message, 'error');
      }
      loadStats();
      loadTableData(activeTab);
    } catch (err: any) {
      showToast(err.message || 'Download failed', 'error');
    } finally {
      setSyncing(false);
    }
  };

  const handleExportBackup = async () => {
    try {
      const json = await db.exportBackup();
      const blob = new Blob([json], { type: 'application/json' });
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `rishabh_tech_db_backup_${new Date().toISOString().slice(0, 10)}.json`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      showToast('Database backup exported to JSON! 💾', 'success');
    } catch (err: any) {
      showToast('Failed to export backup: ' + err.message, 'error');
    }
  };

  const handleImportFile = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = async (event) => {
      try {
        const text = event.target?.result as string;
        const res = await db.importBackup(text);
        if (res.success) {
          showToast(res.message, 'success');
          loadStats();
          loadTableData(activeTab);
        } else {
          showToast(res.message, 'error');
        }
      } catch (err: any) {
        showToast('Failed to import backup: ' + err.message, 'error');
      }
    };
    reader.readAsText(file);
    if (fileInputRef.current) fileInputRef.current.value = '';
  };

  const handleResetDefaults = async () => {
    if (window.confirm('Reset local database back to default sample records?')) {
      await db.resetToDefaults();
      showToast('Local database reset to defaults! 🔄', 'info');
      loadStats();
      loadTableData(activeTab);
    }
  };

  const handleCopySql = () => {
    navigator.clipboard.writeText(SCHEMA_SQL);
    showToast('PostgreSQL schema copied to clipboard! 📋', 'success');
  };

  // Filtered live table items
  const filteredTableData = tableData.filter((item) => {
    if (!tableSearch.trim()) return true;
    const str = JSON.stringify(item).toLowerCase();
    return str.includes(tableSearch.toLowerCase());
  });

  // ==========================================
  // Render Login Gate
  // ==========================================
  if (!isAuthenticated) {
    return (
      <div className="min-h-[70vh] flex items-center justify-center p-4 font-sans">
        <div className="w-full max-w-md bg-slate-900/90 backdrop-blur-2xl border border-slate-700/80 rounded-3xl p-7 sm:p-9 shadow-[0_15px_50px_rgba(0,0,0,0.6)] relative overflow-hidden transition-all">
          <div className="absolute -top-24 -left-24 w-48 h-48 bg-cyan-500/20 rounded-full blur-3xl pointer-events-none" />
          <div className="absolute -bottom-24 -right-24 w-48 h-48 bg-blue-600/20 rounded-full blur-3xl pointer-events-none" />

          <div className="text-center mb-6 relative z-10">
            <div className="w-16 h-16 rounded-2xl bg-gradient-to-tr from-cyan-500 via-blue-600 to-indigo-600 mx-auto flex items-center justify-center text-white shadow-xl shadow-cyan-500/30 mb-3.5 border border-cyan-400/40">
              <Lock style={{ fontSize: '30px' }} />
            </div>
            <h2 className="text-2xl font-black text-white tracking-tight">Database Hub</h2>
            <p className="text-xs text-slate-400 mt-1 max-w-xs mx-auto">
              Secure Administrative Control Center. Credentials verified against local &amp; cloud database users table.
            </p>
          </div>

          {/* Demo Credentials Pill */}
          <div className="mb-5 p-3 rounded-2xl bg-cyan-950/40 border border-cyan-500/30 text-xs text-cyan-300 relative z-10 flex flex-col gap-1 shadow-inner">
            <div className="flex items-center gap-1.5 font-bold text-cyan-200">
              <Shield fontSize="small" />
              <span>Default Database Admin Credentials:</span>
            </div>
            <div className="flex items-center justify-between text-[11px] text-slate-300 pt-1 border-t border-cyan-500/20">
              <span>Username: <strong className="text-white font-mono">rishabh</strong></span>
              <span>Password: <strong className="text-white font-mono">rishi@123</strong></span>
            </div>
          </div>

          <form onSubmit={handleLogin} className="space-y-4 relative z-10">
            {authError && (
              <div className="p-3 bg-red-500/20 border border-red-500/40 rounded-xl text-xs text-red-300 font-medium flex items-center gap-2">
                <ErrorOutline fontSize="small" />
                <span>{authError}</span>
              </div>
            )}

            <div>
              <label className="block text-xs font-bold uppercase tracking-wider text-slate-300 mb-1.5">
                Username
              </label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                  <Person fontSize="small" />
                </div>
                <input
                  type="text"
                  value={authUsername}
                  onChange={(e) => setAuthUsername(e.target.value)}
                  placeholder="Enter database username"
                  className="w-full pl-10 pr-4 py-2.5 bg-slate-800/80 border border-slate-700 rounded-xl text-white text-sm focus:outline-none focus:border-cyan-500 transition-colors"
                  required
                />
              </div>
            </div>

            <div>
              <label className="block text-xs font-bold uppercase tracking-wider text-slate-300 mb-1.5">
                Password
              </label>
              <div className="relative">
                <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                  <VpnKey fontSize="small" />
                </div>
                <input
                  type={showPassword ? 'text' : 'password'}
                  value={authPassword}
                  onChange={(e) => setAuthPassword(e.target.value)}
                  placeholder="Enter database password"
                  className="w-full pl-10 pr-10 py-2.5 bg-slate-800/80 border border-slate-700 rounded-xl text-white text-sm focus:outline-none focus:border-cyan-500 transition-colors"
                  required
                />
                <button
                  type="button"
                  onClick={() => setShowPassword(!showPassword)}
                  className="absolute inset-y-0 right-0 pr-3.5 flex items-center text-slate-400 hover:text-white cursor-pointer"
                >
                  {showPassword ? <VisibilityOff fontSize="small" /> : <Visibility fontSize="small" />}
                </button>
              </div>
            </div>

            <button
              type="submit"
              disabled={authenticating}
              className="w-full py-3 mt-2 bg-gradient-to-r from-blue-600 via-cyan-600 to-teal-500 hover:from-blue-500 hover:to-cyan-400 text-white font-bold rounded-xl shadow-lg shadow-cyan-500/25 transition-all text-sm flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
            >
              {authenticating ? (
                <>
                  <i className="fas fa-spinner fa-spin" />
                  <span>Verifying in Database...</span>
                </>
              ) : (
                <>
                  <Shield fontSize="small" />
                  <span>Unlock Database Hub</span>
                </>
              )}
            </button>

            <div className="text-center pt-2">
              <span className="text-[11px] text-slate-400">
                🔒 Protected by IndexedDB Dexie &amp; Supabase PostgreSQL RLS
              </span>
            </div>
          </form>
        </div>
      </div>
    );
  }

  // ==========================================
  // Render Main Database Hub
  // ==========================================
  return (
    <div className="database-page font-sans">
      {/* Top Header */}
      <div className="db-header">
        <div className="db-title-row">
          <h1>
            <Storage className="text-cyan-400" />
            <span>Database Hub &amp; Cloud Storage Manager</span>
          </h1>

          <div className="flex items-center gap-2 flex-wrap">
            {currentUser && (
              <div className="flex items-center gap-1.5 bg-cyan-500/15 text-cyan-300 border border-cyan-500/35 px-3 py-1.5 rounded-full text-xs font-bold shadow-sm">
                <Person style={{ fontSize: '15px' }} />
                <span>Admin: {currentUser.name || currentUser.username}</span>
              </div>
            )}
            <button
              onClick={handleLogout}
              className="flex items-center gap-1.5 bg-red-500/15 text-red-300 border border-red-500/35 px-3 py-1.5 rounded-full text-xs font-bold hover:bg-red-500/25 transition-colors cursor-pointer"
              title="Lock Database Hub session"
            >
              <ExitToApp style={{ fontSize: '15px' }} />
              <span>Lock Session</span>
            </button>
            <div className="deployment-pill" title="Current Deployment">
              <span className="live-dot"></span>
              <span>Live Deployment: <strong>rajrishabhkr.github.io/dashboard</strong></span>
            </div>
          </div>
        </div>
        <p className="db-subtitle">
          Manage local offline IndexedDB records, test live Supabase PostgreSQL server connections, sync cloud data, and view live database tables.
        </p>
      </div>

      {/* 3 Overview Status Cards */}
      <div className="status-grid">
        <div className="status-card">
          <div className="card-top">
            <div className="card-icon local"><i className="fas fa-hdd"></i></div>
            <span className="badge active">Active &amp; Ready</span>
          </div>
          <h3 className="card-title">Free Local DB (IndexedDB)</h3>
          <p className="card-desc">
            Powered by Dexie.js v2. 100% free, zero configuration, persists offline across app sessions and inside the Android APK.
          </p>
        </div>

        <div className="status-card">
          <div className="card-top">
            <div className="card-icon cloud"><i className="fas fa-cloud"></i></div>
            <span className={`badge ${config.isConfigured ? 'connected' : 'disconnected'}`}>
              {config.isConfigured ? 'Configured & Ready' : 'Not Configured'}
            </span>
          </div>
          <h3 className="card-title">Free Server DB (Supabase)</h3>
          <p className="card-desc">
            Best suited server database for GitHub Pages. Provides free hosted PostgreSQL, REST APIs, and instant client sync.
          </p>
        </div>

        <div className="status-card">
          <div className="card-top">
            <div className="card-icon deploy"><i className="fas fa-globe"></i></div>
            <span className="badge live">Static Deployment</span>
          </div>
          <h3 className="card-title">Current Deployment</h3>
          <p className="card-desc">
            Hosted on GitHub Pages SPA with HTTPS. Direct client architecture connects securely to Supabase with Anon RLS keys.
          </p>
        </div>
      </div>

      {/* Database Statistics Counter Grid */}
      <div className="stats-grid">
        <div className="stat-box">
          <div className="stat-num">{stats.studentsCount}</div>
          <div className="stat-label">Students</div>
        </div>
        <div className="stat-box">
          <div className="stat-num">{stats.teachersCount}</div>
          <div className="stat-label">Teachers</div>
        </div>
        <div className="stat-box">
          <div className="stat-num">{stats.attendanceCount}</div>
          <div className="stat-label">Attendance Records</div>
        </div>
        <div className="stat-box">
          <div className="stat-num">{stats.ipoCount}</div>
          <div className="stat-label">IPO Listings</div>
        </div>
        <div className="stat-box">
          <div className="stat-num">{stats.totalRecords}</div>
          <div className="stat-label">Total DB Items</div>
        </div>
      </div>

      {/* Storage Mode Selector */}
      <div className="db-section-card">
        <h2><i className="fas fa-sliders-h"></i> Storage &amp; Sync Mode</h2>
        <p className="section-subtitle">Choose how the application handles reading and writing data records.</p>

        <div className="mode-options">
          <div
            className={`mode-card ${currentMode === 'local' ? 'selected' : ''}`}
            onClick={() => handleModeChange('local')}
          >
            <div className="mode-top">
              <input
                type="radio"
                name="dbmode"
                checked={currentMode === 'local'}
                onChange={() => handleModeChange('local')}
              />
              <strong>Local Only (IndexedDB)</strong>
            </div>
            <p>100% private to this browser/device. Zero configuration required. Instant speed and offline persistence.</p>
          </div>

          <div
            className={`mode-card ${currentMode === 'hybrid' ? 'selected' : ''}`}
            onClick={() => handleModeChange('hybrid')}
          >
            <div className="mode-top">
              <input
                type="radio"
                name="dbmode"
                checked={currentMode === 'hybrid'}
                onChange={() => handleModeChange('hybrid')}
              />
              <strong>Hybrid (Local + Cloud Sync)</strong>
              <span className="rec-pill">RECOMMENDED</span>
            </div>
            <p>Stores data locally for instant UI updates while automatically syncing changes to your free Supabase cloud DB.</p>
          </div>

          <div
            className={`mode-card ${currentMode === 'cloud' ? 'selected' : ''}`}
            onClick={() => handleModeChange('cloud')}
          >
            <div className="mode-top">
              <input
                type="radio"
                name="dbmode"
                checked={currentMode === 'cloud'}
                onChange={() => handleModeChange('cloud')}
              />
              <strong>Cloud Only (Supabase)</strong>
            </div>
            <p>Reads and writes directly to Supabase PostgreSQL server database. Requires configured credentials.</p>
          </div>
        </div>
      </div>

      {/* Supabase Free Server DB Configuration */}
      <div className="db-section-card">
        <h2><CloudDone /> Free Server DB Configuration (Supabase PostgreSQL)</h2>
        <p className="section-subtitle">
          Connect your free Supabase project to persist data across all devices and the deployed GitHub Pages website.
          Sign up for free at <a href="https://supabase.com" target="_blank" rel="noopener noreferrer" style={{ color: '#38bdf8' }}>supabase.com</a> (no credit card required).
        </p>

        <div className="form-group">
          <label htmlFor="sb-url">Supabase Project URL</label>
          <input
            id="sb-url"
            type="text"
            placeholder="https://tetqtbhgznhemnzzgifu.supabase.co"
            value={inputUrl}
            onChange={(e) => setInputUrl(e.target.value)}
            onBlur={() => {
              const clean = normalizeSupabaseUrl(inputUrl);
              if (clean && clean !== inputUrl) setInputUrl(clean);
            }}
          />
          <div className="form-hint">
            Must be your API URL: <code>https://tetqtbhgznhemnzzgifu.supabase.co</code> (if you paste the dashboard link or project ID, it will auto-format automatically!)
          </div>
        </div>

        <div className="form-group">
          <label htmlFor="sb-key">Supabase Anon Public API Key</label>
          <input
            id="sb-key"
            type="password"
            placeholder="eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9..."
            value={inputKey}
            onChange={(e) => setInputKey(e.target.value)}
          />
          <div className="form-hint">Found under Project Settings &gt; API &gt; Project API keys (anon public)</div>
        </div>

        <div className="btn-row">
          <button
            className="btn btn-secondary"
            onClick={handleTestConnection}
            disabled={testing}
          >
            <i className={`fas ${testing ? 'fa-spinner fa-spin' : 'fa-plug'}`}></i>
            {testing ? 'Testing...' : 'Test Connection'}
          </button>
          <button className="btn btn-primary" onClick={handleSaveCredentials}>
            <i className="fas fa-save"></i> Save Credentials
          </button>
          {config.isConfigured && (
            <button className="btn btn-danger" onClick={handleClearCredentials}>
              <i className="fas fa-trash-alt"></i> Clear Credentials
            </button>
          )}
        </div>

        {testResult && (
          <div className={`alert-box ${testResult.success ? 'success' : 'error'}`}>
            {testResult.success ? <CheckCircle /> : <ErrorOutline />}
            <span>{testResult.message}</span>
          </div>
        )}
      </div>

      {/* Cloud Synchronization & Data Tools */}
      <div className="db-section-card">
        <h2><CloudSync /> Synchronization &amp; Backup Tools</h2>
        <p className="section-subtitle">
          Export full database backups, restore data, or push/pull data between Local IndexedDB and Supabase.
        </p>

        <div className="btn-row">
          <button
            className="btn btn-success"
            onClick={handleSyncToCloud}
            disabled={syncing || !config.isConfigured}
            title={!config.isConfigured ? 'Configure Supabase credentials above first' : ''}
          >
            <i className={`fas ${syncing ? 'fa-spinner fa-spin' : 'fa-cloud-upload-alt'}`}></i>
            Push Local Data to Supabase
          </button>

          <button
            className="btn btn-secondary"
            onClick={handleSyncFromCloud}
            disabled={syncing || !config.isConfigured}
            title={!config.isConfigured ? 'Configure Supabase credentials above first' : ''}
          >
            <i className={`fas ${syncing ? 'fa-spinner fa-spin' : 'fa-cloud-download-alt'}`}></i>
            Pull Supabase Data to Local
          </button>

          <button className="btn btn-secondary" onClick={handleExportBackup}>
            <Backup fontSize="small" /> Export JSON Backup
          </button>

          <button className="btn btn-secondary" onClick={() => fileInputRef.current?.click()}>
            <Restore fontSize="small" /> Restore from JSON
          </button>
          <input
            ref={fileInputRef}
            type="file"
            accept=".json"
            style={{ display: 'none' }}
            onChange={handleImportFile}
          />

          <button className="btn btn-danger" onClick={handleResetDefaults}>
            <Refresh fontSize="small" /> Reset to Sample Data
          </button>
        </div>
      </div>

      {/* LIVE IN-HUB DATABASE BROWSER (NEW COOL FEATURE) */}
      <div className="db-section-card">
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', flexWrap: 'wrap', gap: '10px' }}>
          <div>
            <h2><TableChart /> Live In-Hub Database Browser</h2>
            <p className="section-subtitle">
              Inspect raw database records directly in this management console without leaving the page.
            </p>
          </div>
          <div style={{ display: 'flex', gap: '8px', alignItems: 'center' }}>
            <button
              onClick={() => setShowRawJson(!showRawJson)}
              className="btn btn-secondary"
              style={{ fontSize: '0.8rem', padding: '6px 12px' }}
            >
              <Code fontSize="small" /> {showRawJson ? 'View Table' : 'View JSON'}
            </button>
            <button
              onClick={() => loadTableData(activeTab)}
              className="btn btn-secondary"
              style={{ fontSize: '0.8rem', padding: '6px 12px' }}
              title="Refresh table records"
            >
              <Refresh fontSize="small" /> Refresh
            </button>
          </div>
        </div>

        {/* Table Selector Tabs */}
        <div style={{ display: 'flex', gap: '8px', flexWrap: 'wrap', marginTop: '16px', marginBottom: '16px' }}>
          {(['students', 'teachers', 'attendance', 'ipo', 'users'] as TableTab[]).map((tab) => (
            <button
              key={tab}
              onClick={() => {
                setActiveTab(tab);
                setTableSearch('');
              }}
              style={{
                padding: '8px 16px',
                borderRadius: '10px',
                border: activeTab === tab ? '1px solid #38bdf8' : '1px solid #334155',
                background: activeTab === tab ? 'rgba(56, 189, 248, 0.2)' : 'rgba(15, 23, 42, 0.6)',
                color: activeTab === tab ? '#38bdf8' : '#94a3b8',
                fontWeight: 600,
                fontSize: '0.85rem',
                cursor: 'pointer',
                textTransform: 'capitalize',
                transition: 'all 0.2s',
              }}
            >
              {tab === 'ipo' ? 'IPO Watchlist' : tab} ({
                tab === 'students' ? stats.studentsCount :
                tab === 'teachers' ? stats.teachersCount :
                tab === 'attendance' ? stats.attendanceCount :
                tab === 'ipo' ? stats.ipoCount :
                '1'
              })
            </button>
          ))}
        </div>

        {/* Quick Search */}
        <div style={{ marginBottom: '14px' }}>
          <input
            type="text"
            placeholder={`Filter ${activeTab} records by any keyword...`}
            value={tableSearch}
            onChange={(e) => setTableSearch(e.target.value)}
            style={{
              width: '100%',
              padding: '10px 14px',
              borderRadius: '8px',
              border: '1px solid #334155',
              background: '#0f172a',
              color: '#f8fafc',
              fontSize: '0.85rem',
              boxSizing: 'border-box',
            }}
          />
        </div>

        {tableLoading ? (
          <div style={{ textAlign: 'center', padding: '30px', color: '#94a3b8' }}>
            <i className="fas fa-spinner fa-spin" style={{ fontSize: '1.5rem', marginBottom: '8px', display: 'block' }}></i>
            Loading records from database...
          </div>
        ) : showRawJson ? (
          <pre style={{
            background: '#020617',
            padding: '16px',
            borderRadius: '10px',
            border: '1px solid #1e293b',
            color: '#38bdf8',
            fontSize: '0.8rem',
            overflowX: 'auto',
            maxHeight: '380px',
          }}>
            <code>{JSON.stringify(filteredTableData, null, 2)}</code>
          </pre>
        ) : (
          <div style={{ overflowX: 'auto', borderRadius: '10px', border: '1px solid #334155' }}>
            <table style={{ width: '100%', borderCollapse: 'collapse', fontSize: '0.85rem', textAlign: 'left' }}>
              <thead>
                <tr style={{ background: '#0f172a', borderBottom: '1px solid #334155', color: '#cbd5e1' }}>
                  <th style={{ padding: '10px 14px' }}>#ID</th>
                  {activeTab === 'students' && (
                    <>
                      <th style={{ padding: '10px 14px' }}>Name</th>
                      <th style={{ padding: '10px 14px' }}>Age</th>
                      <th style={{ padding: '10px 14px' }}>Grade</th>
                      <th style={{ padding: '10px 14px' }}>Gender</th>
                      <th style={{ padding: '10px 14px' }}>Email</th>
                    </>
                  )}
                  {activeTab === 'teachers' && (
                    <>
                      <th style={{ padding: '10px 14px' }}>Name</th>
                      <th style={{ padding: '10px 14px' }}>Age</th>
                      <th style={{ padding: '10px 14px' }}>Subject</th>
                      <th style={{ padding: '10px 14px' }}>Gender</th>
                      <th style={{ padding: '10px 14px' }}>Email</th>
                    </>
                  )}
                  {activeTab === 'attendance' && (
                    <>
                      <th style={{ padding: '10px 14px' }}>Name</th>
                      <th style={{ padding: '10px 14px' }}>Role</th>
                      <th style={{ padding: '10px 14px' }}>Gender</th>
                      <th style={{ padding: '10px 14px' }}>Date</th>
                      <th style={{ padding: '10px 14px' }}>Status</th>
                    </>
                  )}
                  {activeTab === 'ipo' && (
                    <>
                      <th style={{ padding: '10px 14px' }}>Company</th>
                      <th style={{ padding: '10px 14px' }}>Issue Size</th>
                      <th style={{ padding: '10px 14px' }}>Price Range</th>
                      <th style={{ padding: '10px 14px' }}>Min Investment</th>
                    </>
                  )}
                  {activeTab === 'users' && (
                    <>
                      <th style={{ padding: '10px 14px' }}>Username</th>
                      <th style={{ padding: '10px 14px' }}>Full Name</th>
                      <th style={{ padding: '10px 14px' }}>Role</th>
                      <th style={{ padding: '10px 14px' }}>Password</th>
                    </>
                  )}
                </tr>
              </thead>
              <tbody>
                {filteredTableData.length === 0 ? (
                  <tr>
                    <td colSpan={6} style={{ textAlign: 'center', padding: '24px', color: '#94a3b8' }}>
                      No records found in this table.
                    </td>
                  </tr>
                ) : (
                  filteredTableData.map((row: any) => (
                    <tr key={row.id} style={{ borderBottom: '1px solid #1e293b', background: 'rgba(15, 23, 42, 0.4)' }}>
                      <td style={{ padding: '10px 14px', color: '#94a3b8', fontFamily: 'monospace' }}>#{row.id}</td>
                      {activeTab === 'students' && (
                        <>
                          <td style={{ padding: '10px 14px', fontWeight: 600, color: '#f8fafc' }}>{row.name}</td>
                          <td style={{ padding: '10px 14px' }}>{row.age}</td>
                          <td style={{ padding: '10px 14px' }}>
                            <span style={{ padding: '2px 8px', borderRadius: '4px', background: 'rgba(56, 189, 248, 0.2)', color: '#38bdf8', fontSize: '0.75rem', fontWeight: 700 }}>
                              {row.grade}
                            </span>
                          </td>
                          <td style={{ padding: '10px 14px' }}>{row.gender}</td>
                          <td style={{ padding: '10px 14px', color: '#94a3b8' }}>{row.email}</td>
                        </>
                      )}
                      {activeTab === 'teachers' && (
                        <>
                          <td style={{ padding: '10px 14px', fontWeight: 600, color: '#f8fafc' }}>{row.name}</td>
                          <td style={{ padding: '10px 14px' }}>{row.age}</td>
                          <td style={{ padding: '10px 14px', color: '#38bdf8', fontWeight: 500 }}>{row.subject}</td>
                          <td style={{ padding: '10px 14px' }}>{row.gender}</td>
                          <td style={{ padding: '10px 14px', color: '#94a3b8' }}>{row.email}</td>
                        </>
                      )}
                      {activeTab === 'attendance' && (
                        <>
                          <td style={{ padding: '10px 14px', fontWeight: 600, color: '#f8fafc' }}>{row.name}</td>
                          <td style={{ padding: '10px 14px' }}>{row.role}</td>
                          <td style={{ padding: '10px 14px' }}>{row.gender}</td>
                          <td style={{ padding: '10px 14px', color: '#94a3b8' }}>{row.date}</td>
                          <td style={{ padding: '10px 14px' }}>
                            <span style={{
                              padding: '2px 8px',
                              borderRadius: '4px',
                              fontSize: '0.75rem',
                              fontWeight: 700,
                              background: row.status === 'Present' ? 'rgba(34, 197, 94, 0.2)' : row.status === 'Late' ? 'rgba(234, 179, 8, 0.2)' : 'rgba(239, 68, 68, 0.2)',
                              color: row.status === 'Present' ? '#4ade80' : row.status === 'Late' ? '#fde047' : '#f87171',
                            }}>
                              {row.status}
                            </span>
                          </td>
                        </>
                      )}
                      {activeTab === 'ipo' && (
                        <>
                          <td style={{ padding: '10px 14px', fontWeight: 700, color: '#f8fafc' }}>{row.company}</td>
                          <td style={{ padding: '10px 14px', color: '#38bdf8' }}>{row.issueSize}</td>
                          <td style={{ padding: '10px 14px' }}>{row.priceRange}</td>
                          <td style={{ padding: '10px 14px', color: '#4ade80' }}>{row.minInvestment}</td>
                        </>
                      )}
                      {activeTab === 'users' && (
                        <>
                          <td style={{ padding: '10px 14px', fontWeight: 700, color: '#38bdf8' }}>{row.username}</td>
                          <td style={{ padding: '10px 14px', color: '#f8fafc' }}>{row.name}</td>
                          <td style={{ padding: '10px 14px' }}>
                            <span style={{ padding: '2px 8px', borderRadius: '4px', background: 'rgba(168, 85, 247, 0.2)', color: '#c084fc', fontSize: '0.75rem', fontWeight: 700 }}>
                              {row.role}
                            </span>
                          </td>
                          <td style={{ padding: '10px 14px', color: '#94a3b8', letterSpacing: '2px' }}>{row.passwordHash}</td>
                        </>
                      )}
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* SQL Schema for Supabase Setup */}
      <div className="db-section-card">
        <h2><Code /> Supabase PostgreSQL Setup Schema</h2>
        <p className="section-subtitle">
          Run this SQL script once in your Supabase project dashboard (SQL Editor) to create the tables, users, and public RLS policies.
        </p>

        <div className="btn-row" style={{ marginTop: 0, marginBottom: '16px' }}>
          <button className="btn btn-primary" onClick={handleCopySql}>
            <i className="fas fa-copy"></i> Copy SQL Schema
          </button>
          <button className="btn btn-secondary" onClick={() => setShowSql(!showSql)}>
            <i className={`fas ${showSql ? 'fa-chevron-up' : 'fa-chevron-down'}`}></i>
            {showSql ? 'Hide SQL Code' : 'View SQL Code'}
          </button>
        </div>

        {showSql && (
          <pre className="schema-viewer">
            <code>{SCHEMA_SQL}</code>
          </pre>
        )}
      </div>

      {/* Standalone Local Server Info */}
      <div className="db-section-card">
        <h2><i className="fas fa-server"></i> Standalone Local Node.js DB Server (Optional)</h2>
        <p className="section-subtitle">
          If you prefer running a backend REST API server locally on your machine, you can run our included zero-dependency Node server:
        </p>
        <div style={{ background: '#020617', padding: '14px', borderRadius: '8px', fontFamily: 'monospace', color: '#38bdf8', border: '1px solid #1e293b' }}>
          npm run server
        </div>
        <p style={{ fontSize: '0.85rem', color: '#94a3b8', marginTop: '10px', marginBottom: 0 }}>
          This runs an HTTP server at <code>http://localhost:5000</code> persisting data to <code>server/local_db.json</code>.
        </p>
      </div>
    </div>
  );
};

