-- ========================================================
-- RISHABH TECH DASHBOARD - SUPABASE POSTGRESQL SCHEMA
-- Free Server Database for GitHub Pages & Web Deployment
-- ========================================================

-- 1. Create Students Table
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    age INT DEFAULT 18,
    grade TEXT DEFAULT 'A',
    gender TEXT DEFAULT 'Male',
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Teachers Table
CREATE TABLE IF NOT EXISTS public.teachers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    age INT DEFAULT 35,
    subject TEXT NOT NULL,
    gender TEXT DEFAULT 'Female',
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Attendance Table
CREATE TABLE IF NOT EXISTS public.attendance (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    role TEXT DEFAULT 'Student',
    gender TEXT DEFAULT 'Male',
    date TEXT NOT NULL,
    status TEXT DEFAULT 'Present',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Create IPO Watchlist Table
CREATE TABLE IF NOT EXISTS public.ipo_list (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    company TEXT NOT NULL,
    issue_size TEXT,
    price_range TEXT,
    min_investment TEXT,
    logo_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ========================================================
-- ROW LEVEL SECURITY (RLS) CONFIGURATION
-- Allows safe, direct read/write from GitHub Pages frontend
-- using your public Supabase Anon key
-- ========================================================

ALTER TABLE public.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.teachers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ipo_list ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running
DROP POLICY IF EXISTS "Public full access students" ON public.students;
DROP POLICY IF EXISTS "Public full access teachers" ON public.teachers;
DROP POLICY IF EXISTS "Public full access attendance" ON public.attendance;
DROP POLICY IF EXISTS "Public full access ipo_list" ON public.ipo_list;

-- Create open policies for anon users
CREATE POLICY "Public full access students" ON public.students FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access teachers" ON public.teachers FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access attendance" ON public.attendance FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public full access ipo_list" ON public.ipo_list FOR ALL USING (true) WITH CHECK (true);

